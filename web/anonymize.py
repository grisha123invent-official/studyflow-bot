"""
Анонимизация студента для редакторской панели.

Редактор НЕ должен видеть никаких персональных данных студента
(защита от увода клиента + 152-ФЗ).
"""


def student_alias(user_id: int) -> str:
    """Возвращает анонимный идентификатор студента вида `student_0042`."""
    return f"student_{user_id:04d}"
