"""
Построитель промпта для Claude.ai на основе брифа студента.
Промпт копируется администратором вручную в Claude.ai.
"""
from db.models import Order


# Структуры по типу работы
WORK_STRUCTURES = {
    "kursovaya": (
        "введение (актуальность темы, цели, задачи), "
        "глава 1 — теоретическая часть (3–4 параграфа), "
        "глава 2 — практическая/аналитическая часть (3–4 параграфа), "
        "заключение (выводы по каждой задаче), "
        "список использованных источников"
    ),
    "referat": (
        "введение (актуальность, цели), "
        "раздел 1, раздел 2, раздел 3, раздел 4 (основное содержание по теме), "
        "заключение, "
        "список литературы"
    ),
    "statya": (
        "аннотация (3–5 предложений), "
        "ключевые слова (5–7 слов), "
        "введение, "
        "основная часть (2–3 раздела с подзаголовками), "
        "выводы / заключение, "
        "список литературы (ГОСТ)"
    ),
    "domashka": (
        "постановка задачи, "
        "решение с подробными пояснениями каждого шага, "
        "ответ"
    ),
    "konspekt": (
        "краткое введение по теме, "
        "основные понятия и определения, "
        "ключевые тезисы по разделам, "
        "выводы"
    ),
    "prezentaciya": (
        "титульный слайд (тема, предмет, автор), "
        "содержание/план презентации, "
        "вводный слайд (актуальность темы), "
        "основные слайды с содержанием по разделам (5–10 слайдов), "
        "слайд с выводами, "
        "список использованных источников"
    ),
    "drugoe": (
        "введение, "
        "основная часть (разделы по логике темы), "
        "заключение"
    ),
}

# Человекочитаемые названия типов работ (для промпта)
WORK_TYPE_DISPLAY = {
    "kursovaya": "курсовую работу",
    "referat": "реферат",
    "statya": "научную статью",
    "domashka": "домашнее задание",
    "konspekt": "конспект",
    "prezentaciya": "презентацию",
    "drugoe": "учебную работу",
}


def _calc_sources(pages: int) -> int:
    """Рассчитывает минимальное количество источников по числу страниц"""
    return max(5, pages // 5)


def build_prompt(order: Order, has_student_file: bool = False) -> str:
    """
    Строит готовый промпт для Claude.ai по брифу заказа.

    :param order: объект заказа из БД
    :param has_student_file: True если студент загрузил свой шаблон/методичку
    :return: текст промпта
    """
    work_type = order.work_type or "drugoe"
    work_display = WORK_TYPE_DISPLAY.get(work_type, "учебную работу")
    structure = WORK_STRUCTURES.get(work_type, WORK_STRUCTURES["drugoe"])
    pages = order.pages or 20
    sources_count = _calc_sources(pages)

    # Определяем курс (заглушка — студент не указывает курс в брифе)
    course = "2"

    lines = [
        f"Ты студент {course} курса, тебе задали написать {work_display} "
        f"по предмету «{order.subject}» на тему: «{order.topic}».",
        "",
        f"Работа должна включать: {structure}.",
        "",
        f"Объём: не менее {pages} страниц (без учёта списка литературы и приложений).",
        f"Источники: не менее {sources_count} источников, год публикации 2020 и позднее.",
        "Оформление: ГОСТ 7.32 / ГОСТ Р 7.0.5-2008, Times New Roman 14, "
        "поля — лево 30мм, верх/низ 20мм, право 15мм, межстрочный интервал 1,5.",
    ]

    if order.comment:
        lines += [
            "",
            "Дополнительные требования от студента:",
            order.comment,
        ]

    if has_student_file:
        lines += [
            "",
            "Оформи работу точно так же, как в прикреплённом файле.",
        ]

    lines += [
        "",
        "Пиши на русском языке. Текст должен быть уникальным, не скопированным из интернета.",
        "Не используй общие фразы — текст должен быть содержательным и академическим.",
    ]

    return "\n".join(lines)
